"""Deterministic replay/backtest runner — roadmap Phase 8.

The runner ORCHESTRATES landed deterministic code; it mints no protected object itself.
For one ``ReplayScenario`` it walks the real pipeline, never bypassing a boundary:

    strategy.generate(ctx)                      # candidates only (fail-closed on data)
      -> GatewayRequest -> ExecutionGateway.validate()   # the only ValidatedTradeIntent path
      -> mint_order_ticket()                    # the only OrderTicket path
      -> record submit attempt (BEFORE broker)  # Phase-4 persist-before-call
      -> mint_broker_submit_intent()            # the only BrokerSubmitIntent path
      -> broker.submit_order()                  # fakes accept BrokerSubmitIntent only
      -> mint_execution_report()                # the only ExecutionReport path
      -> audit store append                     # rejections/failures audited, never dropped

Determinism: every timestamp is the scenario's explicit ``as_of`` / caller ``recorded_at``;
no wall clock, no randomness, no network. Fail-closed: a missing-data strategy error, a
gateway rejection, a malformed gateway assembly, or a broker failure all produce a typed
result and an audit record — never a silent drop and never a crash out of the runner.

Safety boundary (Constitution §0.1; AGENTS.md; roadmap Do-Not-Cross): the scenario supplies
only the (deterministic) strategy inputs and safety state. The candidate is generated by
deterministic strategy code, and every protected object is minted exclusively by the
gateway/routing/submission helpers. Nothing here lets a raw dict, prose, or an
earlier-stage object become a protected execution object.
"""

